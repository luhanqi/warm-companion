def ex(user, assistant, **sys_kw):
    extra_user = sys_kw.pop("history", None)
    messages = [{"role": "system", "content": build_system(**sys_kw)}]
    if extra_user:
        messages.extend(extra_user)
    messages.append({"role": "user", "content": user})
    messages.append({"role": "assistant", "content": assistant})
    return {"messages": messages}


def expand(users, assistant, **sys_kw):
    return [ex(u, assistant, **sys_kw) for u in users]


